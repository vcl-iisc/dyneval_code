def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if args.prepare_only and args.train_only:
        raise SystemExit("Use only one of --prepare-only or --train-only.")

    train_file_was_default = args.train_file is None
    val_file_was_default = args.val_file is None
    if args.data_dir == DEFAULT_DATA_DIR:
        if args.t2ia_task == "question_generation":
            args.data_dir = DEFAULT_QUESTION_DATA_DIR
        elif args.t2ia_task == "question_generation_single":
            args.data_dir = DEFAULT_SINGLE_QUESTION_DATA_DIR
        elif args.t2ia_task == "mixed":
            args.data_dir = DEFAULT_MIXED_DATA_DIR
        elif args.t2ia_task == "mixed_with_single_questions":
            args.data_dir = Path("data/sft/qwen3vl_t2ia_mixed_single_sft_data")
        elif args.t2ia_task == "evaluation":
            args.data_dir = DEFAULT_EVALUATION_DATA_DIR
    if train_file_was_default:
        args.train_file = args.data_dir / "train.jsonl"
    if val_file_was_default:
        args.val_file = args.data_dir / "val.jsonl"
    if args.finetune_mode == "full" and args.output_dir == DEFAULT_OUTPUT_DIR:
        args.output_dir = DEFAULT_FULL_OUTPUT_DIR

    if not args.train_only:
        manifest = prepare_t2ia_sft(
            source_json=args.source_json,
            output_dir=args.data_dir,
            val_ratio=args.val_ratio,
            seed=args.seed,
            limit=args.limit,
            t2ia_task=args.t2ia_task,
            image_root=args.image_root,
        )
        print(json.dumps(manifest, indent=2))

    if args.prepare_only:
        return

    if not args.train_file.exists():
        raise SystemExit(f"Missing train file: {args.train_file}. Run without --train-only first.")

    train_t2ia(args)


if __name__ == "__main__":
    main()
